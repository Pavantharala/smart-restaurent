// ============================================================
// SMART CAFE - MENU TYPES
// ============================================================
//
// Central data model for Smart Cafe menu items.
//
// Used by:
// - Customer Menu
// - Product Details
// - Cart
// - Staff Kitchen
// - Admin Menu
// - Future Backend / Database
//
// ============================================================

// ============================================================
// MENU CATEGORY
// ============================================================

export type MenuCategory =
  | "food"
  | "drinks"
  | "snacks"
  | "desserts"
  | "specials";

// ============================================================
// FOOD TYPE
// ============================================================
//
// Food type is only used when it makes sense.
//
// Food:
//   - veg
//   - non-veg
//
// Snacks:
//   - veg
//   - non-veg
//
// Drinks:
//   - no food type
//
// Desserts:
//   - no food type
//
// Specials:
//   - optional
//
// ============================================================

export type FoodType = "veg" | "non-veg";

// ============================================================
// CUSTOMIZATION
// ============================================================

export interface MenuCustomization {
  id: string;
  name: string;
  price?: number;
}

// ============================================================
// MAIN MENU ITEM
// ============================================================

export interface MenuItem {
  // ----------------------------------------------------------
  // Unique item ID
  // ----------------------------------------------------------

  id: string;

  // ----------------------------------------------------------
  // Display information
  // ----------------------------------------------------------

  name: string;

  category: MenuCategory;

  description?: string;

  details?: string;

  // ----------------------------------------------------------
  // FOOD TYPE
  // ----------------------------------------------------------
  //
  // Optional because Drinks and Desserts do not use it.
  //
  // Food and Snacks should normally have it.
  //
  // Specials may optionally have it.
  //
  // ----------------------------------------------------------

  foodType?: FoodType;

  // ----------------------------------------------------------
  // PRICE
  // ----------------------------------------------------------

  price: number;

  originalPrice?: number;

  // ----------------------------------------------------------
  // IMAGE
  // ----------------------------------------------------------

  image?: string;

  // ----------------------------------------------------------
  // CUSTOMIZATIONS
  // ----------------------------------------------------------

  customizations?: MenuCustomization[];

  // ----------------------------------------------------------
  // AVAILABILITY
  // ----------------------------------------------------------

  isAvailable: boolean;

  // ----------------------------------------------------------
  // PREPARATION TIME
  // ----------------------------------------------------------

  preparationTime?: number;

  // ----------------------------------------------------------
  // SEARCH / RECOMMENDATION TAGS
  // ----------------------------------------------------------

  tags?: string[];
}